// Separator: 1 ASCII space on each side of the │. Together with the
// 1-char space already in adjacent chunks this gives a comfortable 2-col
// gap; the previous 2+2 left visible whitespace gaps that competed with
// the already-padded labels.
const SEP = " " + ESC + C_MUTED + "m\\u2502" + RESET_SEQ + " ";
const HORIZ_MIN_WIDTH = 110;
const NARROW_MIN_WIDTH = 80;
// How the 输入/输出/缓存 breakdown trades off against row count.
//   auto (default) — responsive: drop the breakdown whenever keeping it would
//                    cost an extra row, keep it on a tie. Narrow terminals then
//                    spend their width on the bars / 上下文 instead of on detail.
//   full           — always keep the breakdown, even if it wraps to more rows.
//   compact        — never show the breakdown.
const TAIL_MODE = (() => {
  const v = String(process.env.MCODE_QUOTA_TAIL || "").toLowerCase();
  return v === "compact" || v === "full" ? v : "auto";
})();

// Render a single quota line at the widest bar that still fits the width.
// For truly tiny terminals (sub-MIN_BAR_WIDTH) shrink the bar down to 1 char
// rather than overflow — the user sees a sliver of the bar instead of a
// clipped row, and the percent / labels still convey status.
function fit(build, width) {
  for (let bar = MAX_BAR_WIDTH; bar >= MIN_BAR_WIDTH; bar--) {
    const s = build(bar);
    if (dw(s) <= width) return s;
  }
  for (let bar = MIN_BAR_WIDTH - 1; bar >= 1; bar--) {
    const s = build(bar);
    if (dw(s) <= width) return s;
  }
  return build(MIN_BAR_WIDTH);
}

globalThis.__mcodeQuotaRender = function (width) {
  if (width == null || !Number.isFinite(width) || width < 0) width = 0;
  // Re-kick the session fetch when the TUI has just exposed its shellState
  // for the first time. The eager-start from import time runs before the
  // TUI has wired up globalThis.__mcodeShellState, so the first session
  // fetch would no-op. The render hook below is when the shell becomes
  // available, so we trigger a session fetch here.
  if (globalThis.__mcodeShellState?.agentSessionId &&
      (!session.sessionId || session.sessionId !== globalThis.__mcodeShellState.agentSessionId)) {
    session = { ...session, sessionId: null, fetchedAt: 0 };
    pendingPlaceholders.session = true;
    // fire-and-forget; resolves into requestRefresh() once done
    fetchSessionOnce();
  }
  // 会话 tokens and 上下文 share one tail so either can render without the other.
  const buildTail = (compact) => {
    const parts = [renderSessionChunk(compact), renderContextChunk()].filter(Boolean);
    return parts.join(SEP);
  };
  // Prefer the full breakdown; fall back to the compact form when the terminal
  // is too narrow for it.
  const tailFor = (w) => {
    const full = buildTail(false);
    if (dw(full) <= w) return full;
    return buildTail(true);
  };
  const lines = [];
  if (raw.valid) {
    // Two logical sections that render as separate rows:
    //   top     — 5小时使用量 / 周使用量 (the "token usage" the user wants on
    //             its own line, hugging the mcode status bar above it)
    //   bottom  — 会话 tokens [breakdown] │ 上下文 (the "token counts" block)
    //
    // Each section is independently responsive: the top either combines the
    // two bars on one line (when wide enough) or stacks them on two lines
    // with aligned labels; the bottom is the legacy compact/full/auto tail.
    // The two sections never share a row, so 会话 tokens is never pushed off
    // screen just because the bars needed more room.
    const labelWidth = Math.max(dw(L_LABEL_5H), dw(L_LABEL_WEEK));

    // 5h / week row builders. q* keeps reset times for stacked rows; q*n
    // drops them when the bars share a single row. labelWidth keeps the
    // 5h and 周 prefixes visually aligned when stacked.
    const q5  = (bar) => renderOne(L_LABEL_5H, raw.dRem, raw.dReset, bar, labelWidth);
    const qw  = (bar) => renderOne(L_LABEL_WEEK, raw.wRem, raw.wReset, bar, labelWidth);
    const q5n = (bar) => renderOne(L_LABEL_5H, raw.dRem, "", bar, labelWidth);
    const qwn = (bar) => renderOne(L_LABEL_WEEK, raw.wRem, "", bar, labelWidth);

    // Top section (token usage): one combined row when it fits, otherwise
    // two stacked rows with aligned labels. Reset times are kept on every
    // variant that fits — they tell the user when the bucket refreshes.
    const topCombined = (bar) => q5(bar) + SEP + qw(bar);
    const topOneRow = fit(topCombined, width);
    let topRows;
    if (dw(topOneRow) <= width) {
      topRows = [topOneRow];
    } else {
      // Combined row with reset times overflows: try the stacked two-row
      // form where each section gets its own row.
      const stacked = [fit(q5, width), fit(qw, width)];
      if (stacked.every((r) => dw(r) <= width)) {
        topRows = stacked;
      } else {
        // Stacked with reset also overflows: drop reset times to gain room.
        const q5n = (bar) => renderOne(L_LABEL_5H, raw.dRem, "", bar, labelWidth);
        const qwn = (bar) => renderOne(L_LABEL_WEEK, raw.wRem, "", bar, labelWidth);
        const stackedNoReset = [fit(q5n, width), fit(qwn, width)];
        if (stackedNoReset.every((r) => dw(r) <= width)) {
          topRows = stackedNoReset;
        } else {
          // Truly tiny (< ~50): drop the percent to keep the bar visible.
          // Walk through label padding and bar width together to find ANY
          // rendering that fits, however degraded. The bar stays a bar — the
          // label can be aggressively truncated.
          let best = null;
          for (const lw of [labelWidth, 4, 0]) {
            const q5s = (bar) => label(L_LABEL_5H) + " " + buildBar(raw.dRem, bar).text;
            const qws = (bar) => paddedLabel(L_LABEL_WEEK, lw) + " " + buildBar(raw.wRem, bar).text;
            const rows = [fit(q5s, width), fit(qws, width)];
            if (rows.every((r) => dw(r) <= width)) { topRows = rows; best = null; break; }
            best = rows;
          }
          if (best) topRows = best;
          // Final fallback for sub-20-col: shrink the labels themselves.
          if (topRows.some((r) => dw(r) > width)) {
            for (const chars of [Math.max(2, Math.floor(width / 4)), 2, 1]) {
              const trunc5 = L_LABEL_5H.slice(0, chars);
              const truncW = L_LABEL_WEEK.slice(0, chars);
              const q5s = (bar) => label(trunc5) + " " + buildBar(raw.dRem, bar).text;
              const qws = (bar) => label(truncW) + " " + buildBar(raw.wRem, bar).text;
              const rows = [fit(q5s, width), fit(qws, width)];
              if (rows.every((r) => dw(r) <= width)) { topRows = rows; break; }
              topRows = rows; // keep the most aggressive attempt as last resort
            }
          }
        }
      }
    }

    // v3.2: 3 independent lines — 4-chunk / 5h/周 / 今日. Order top-to-bottom
    // matches the v3.1.0 layout (会话上下文 in the most-prominent slot,
    // quota bars hugging mcode's status bar, today's LLM-by-model stats at
    // the bottom). mcode's launcher framework actually accepts any number of
    // elements; the v3.2.0 first ship mistakenly merged 5h/周+今日 into one
    // line based on a stderr-debug misread — see DECISIONS D28.
    const join = (...chunks) => chunks.filter(Boolean).join(SEP);
    const placeholder = (label) => muted(label + " …");
    const sessionFull = renderSessionChunk(false) || (pendingPlaceholders.session ? placeholder("会话 tokens") : null);
    const sessionCompact = renderSessionChunk(true) || sessionFull;
    const ctx = renderContextChunk() || (pendingPlaceholders.context ? placeholder("上下文") : null);
    const hit = renderCacheHitChunk() || (pendingPlaceholders.session ? placeholder("缓存命中") : null);
    const turn = renderTurnCountChunk() || (pendingPlaceholders.session ? placeholder("轮数") : null);

    const buildCandidates = (allowDetail) => {
      const list = [];
      if (allowDetail && sessionFull && ctx) {
        list.push(join(sessionFull, ctx, hit, turn));
        list.push(join(sessionFull, ctx, hit));
        list.push(join(sessionFull, ctx, turn));
        list.push(join(sessionFull, ctx));
      }
      if (sessionCompact && ctx) {
        list.push(join(sessionCompact, ctx, hit, turn));
        list.push(join(sessionCompact, ctx, hit));
        list.push(join(sessionCompact, ctx, turn));
        list.push(join(sessionCompact, ctx));
      }
      if (allowDetail && sessionFull) list.push(sessionFull);
      if (sessionCompact) list.push(sessionCompact);
      if (ctx) list.push(ctx);
      return list;
    };

    const topRowCandidates = (() => {
      if (TAIL_MODE === "compact") return buildCandidates(false);
      if (TAIL_MODE === "full") return buildCandidates(true);
      const detailList = buildCandidates(true);
      const compactList = buildCandidates(false);
      const detailFits = detailList.some((c) => dw(c) <= width);
      return detailFits ? detailList : compactList;
    })();

    if (topRowCandidates.some((c) => dw(c) <= width)) {
      const fits = topRowCandidates.filter((c) => dw(c) <= width);
      fits.sort((a, b) => dw(b) - dw(a));
      lines.push(fits[0]);
    } else {
      const coreLine = sessionFull || sessionCompact || ctx || "";
      lines.push(coreLine);
      const tailPieces = [ctx, hit, turn].filter(Boolean);
      let buf = "";
      for (const p of tailPieces) {
        const candidate = buf ? buf + SEP + p : p;
        if (dw(candidate) <= width) {
          buf = candidate;
        } else {
          if (buf) lines.push(buf);
          buf = p;
        }
      }
      if (buf && !lines.includes(buf)) lines.push(buf);
    }

    // 5h/周 bars (separate line, with reset times when wide)
    lines.push(...topRows);

    // 今日 (per-LLM-model) — separate line below 5h/周
    const todayRows = renderTodayByModelRow(width);
    if (todayRows.length > 0) {
      lines.push(...todayRows);
    } else if (placeholderToday()) {
      lines.push(placeholderToday());
    }
  } else {
    // No quota data yet: 4-chunk placeholders + 今日 placeholder.
    // We still try to render 4-chunk so the user sees structure while
    // waiting for mmx to return; the placeholders show "..." for the
    // chunks that haven't filled.
    const join = (...chunks) => chunks.filter(Boolean).join(SEP);
    const placeholder = (label) => muted(label + " …");
    const sessionFull = renderSessionChunk(false) || (pendingPlaceholders.session ? placeholder("会话 tokens") : null);
    const sessionCompact = renderSessionChunk(true) || sessionFull;
    const ctx = renderContextChunk() || (pendingPlaceholders.context ? placeholder("上下文") : null);
    const hit = renderCacheHitChunk() || (pendingPlaceholders.session ? placeholder("缓存命中") : null);
    const turn = renderTurnCountChunk() || (pendingPlaceholders.session ? placeholder("轮数") : null);
    const tryList = [];
    if (sessionFull && ctx) tryList.push(join(sessionFull, ctx, hit, turn));
    if (sessionCompact && ctx) tryList.push(join(sessionCompact, ctx, hit, turn));
    if (sessionFull) tryList.push(sessionFull);
    if (sessionCompact) tryList.push(sessionCompact);
    if (ctx) tryList.push(ctx);
    for (const c of tryList) if (dw(c) <= width) { lines.push(c); break; }

    const todayRows = renderTodayByModelRow(width);
    if (todayRows.length > 0) {
      lines.push(...todayRows);
    } else if (placeholderToday()) {
      lines.push(placeholderToday());
    }
  }
  // First render is a reliable "this is the real TUI" signal — start then.
  if (!started) start();
  return lines;
};

function requestRefresh() {
  const now = Date.now();
  if (now - lastRefreshAt < REFRESH_MIN_INTERVAL_MS) return;
  lastRefreshAt = now;
  const w = globalThis.__mcodeQuotaWidget;
  try {
    if (w && typeof w.requestRender === "function") w.requestRender();
  } catch {}
}

