let sqliteModPromise = null;
const SQLITE_DEFAULT_PATH = process.env.MCODE_QUOTA_SQLITE
  || (process.env.HOME || "~") + "/.minimax/v2/sqlite/runtime-state.sqlite";
const SQLITE_SESSION_SQL = "SELECT " +
  "COALESCE(SUM(input_tokens), 0) AS inputTokens, " +
  "COALESCE(SUM(output_tokens), 0) AS outputTokens, " +
  "COALESCE(SUM(reasoning_tokens), 0) AS reasoningTokens, " +
  "COALESCE(SUM(cache_read_tokens), 0) AS cacheReadTokens, " +
  "COALESCE(SUM(cache_write_tokens), 0) AS cacheWriteTokens, " +
  "COALESCE(SUM(cost_usd), 0) AS costUsd, " +
  "COUNT(DISTINCT turn_id) AS turns " +
  "FROM local_runtime_token_usage WHERE session_id = ?";

let sqliteDb = null;
let sqliteDbPath = null;
let sqliteColumns = null;   // resolved column names from the live table

// Discover the actual column names the mcode runtime uses. We support
// both the current schema and a few likely renames. Cache the result for
// the life of the sidecar.
async function resolveSqliteColumns(db) {
  if (sqliteColumns) return sqliteColumns;
  let cols;
  try {
    cols = db.prepare("PRAGMA table_info(local_runtime_token_usage)").all();
  } catch {
    return null;
  }
  const names = new Set(cols.map(c => c.name));
  const pick = (candidates) => {
    for (const c of candidates) if (names.has(c)) return c;
    return null;
  };
  const resolved = {
    input:        pick(["input_tokens", "inputTokens", "input"]),
    output:       pick(["output_tokens", "outputTokens", "output"]),
    reasoning:    pick(["reasoning_tokens", "reasoningTokens", "reasoning"]),
    cacheRead:    pick(["cache_read_tokens", "cacheReadTokens", "cacheRead", "cache_read"]),
    cacheWrite:   pick(["cache_write_tokens", "cacheWriteTokens", "cacheWrite", "cache_write"]),
    cost:         pick(["cost_usd", "costUsd", "cost"]),
    turnId:       pick(["turn_id", "turnId", "turn"]),
    session:      pick(["session_id", "sessionId", "session"]),
  };
  if (!resolved.input || !resolved.output || !resolved.cacheRead || !resolved.session) {
    return null;   // essential columns missing; abort
  }
  sqliteColumns = resolved;
  return resolved;
}

const buildSessionSql = (cols) => {
  // Build the SELECT with COALESCE on every resolved column, with
  // friendly aliases. Inputs not in the live table default to 0.
  // NOTE: this file is itself wrapped in an outer template literal, so any
  // inner template literals (backticks) would be misinterpreted. Use plain
  // string concatenation everywhere inside this function.
  const c = (name, def) => "COALESCE(" + name + ", " + def + ")";
  const turns = cols.turnId
    ? "COUNT(DISTINCT " + cols.turnId + ") AS turns"
    : "0 AS turns";
  return "SELECT " +
    c(cols.input, "0") + " AS inputTokens, " +
    c(cols.output, "0") + " AS outputTokens, " +
    c(cols.reasoning || "0", "0") + " AS reasoningTokens, " +
    c(cols.cacheRead, "0") + " AS cacheReadTokens, " +
    c(cols.cacheWrite || "0", "0") + " AS cacheWriteTokens, " +
    c(cols.cost || "0", "0") + " AS costUsd, " +
    turns + " " +
    "FROM local_runtime_token_usage WHERE " + cols.session + " = ?";
};

async function fetchSessionFromSqlite(sessionId) {
  try {
    if (!sqliteModPromise) sqliteModPromise = import("node:sqlite");
    const { DatabaseSync } = await sqliteModPromise;
    if (!sqliteDb || sqliteDbPath !== SQLITE_DEFAULT_PATH) {
      if (sqliteDb) { try { sqliteDb.close(); } catch {} }
      sqliteDb = new DatabaseSync(SQLITE_DEFAULT_PATH, { readOnly: true });
      sqliteDbPath = SQLITE_DEFAULT_PATH;
    }
    const cols = await resolveSqliteColumns(sqliteDb);
    if (!cols) return null;
    const sql = buildSessionSql(cols);
    const row = sqliteDb.prepare(sql).get(sessionId);
    if (!row) return null;
    return {
      inputTokens: Number(row.inputTokens ?? 0),
      outputTokens: Number(row.outputTokens ?? 0),
      reasoningTokens: Number(row.reasoningTokens ?? 0),
      cacheReadTokens: Number(row.cacheReadTokens ?? 0),
      cacheWriteTokens: Number(row.cacheWriteTokens ?? 0),
      costUsd: Number(row.costUsd ?? 0),
      turns: Number(row.turns ?? 0),
    };
  } catch {
    return null;
  }
}

const sumTotal = (s) => {
  if (!s) return 0;
  const n = (x) => (Number.isFinite(Number(x)) ? Number(x) : 0);
  return n(s.inputTokens) + n(s.outputTokens) + n(s.cacheReadTokens);
};

async function fetchSessionOnce() {
  const runtime = globalThis.__mcodeRuntime;
  const shell = globalThis.__mcodeShellState;
  if (!shell) return;
  const sessionId = shell.agentSessionId;
  if (!sessionId) return;
  if (session.sessionId === sessionId && Date.now() - session.fetchedAt < SESSION_TTL_MS) return;

  // Race the runtime API and the sqlite fallback in parallel. The runtime
  // call is in-process and usually fast but occasionally returns zeros
  // (before the first turn is flushed); the sqlite query is the source of
  // truth and always works, so whichever lands first wins, and the slower
  // one's result is discarded.
  const runtimeP = (async () => {
    try {
      const fn = runtime?.getSessionUsageSummary;
      if (typeof fn !== "function") return null;
      const result = await Promise.resolve().then(() => fn.call(runtime, sessionId));
      if (result && typeof result === "object" && sumTotal(result) > 0) return result;
    } catch {}
    return null;
  })();
  const sqliteP = fetchSessionFromSqlite(sessionId);
  const [runtimeRes, sqliteRes] = await Promise.allSettled([runtimeP, sqliteP]);
  const fromRuntime = runtimeRes.status === "fulfilled" ? runtimeRes.value : null;
  const fromSqlite = sqliteRes.status === "fulfilled" ? sqliteRes.value : null;
  // Prefer the runtime value when both have real numbers; otherwise use
  // whichever is non-empty.
  const summary = fromRuntime || fromSqlite;
  const source = fromRuntime ? "runtime" : (fromSqlite ? "sqlite" : null);
  if (!summary) {
    session = { ...session, sessionId, fetchedAt: Date.now() };
    requestRefresh();
    return;
  }
  const input = Number(summary.inputTokens ?? 0);
  const output = Number(summary.outputTokens ?? 0);
  const cache = Number(summary.cacheReadTokens ?? 0);
  const reasoning = Number(summary.reasoningTokens ?? 0);
  // Cache hit rate: cache_read / (cache_read + fresh_input). A turn with
  // zero fresh input and some cache_read is 100% hit; both zero = no data.
  const hitDenom = cache + input;
  const cacheHit = hitDenom > 0 ? cache / hitDenom : null;
  session = {
    valid: true,
    total: input + output + cache,
    input, output, cache, reasoning,
    sessionId,
    turns: Number(summary.turns ?? 0),
    cacheHit,
    source,
    fetchedAt: Date.now(),
  };
  pendingPlaceholders.session = false;
  requestRefresh();
}

// ----------------------------------------------------------------------------
// Today (since local 00:00): per-LLM-model token totals.
//
// mcode 0.3.11's local_runtime_token_usage.model column is always NULL,
// so the model name lives in
// local_runtime_message_rows.data_json.context_usage_telemetry.model
// for assistant messages. We join via turn_id in JS to keep the query
// simple and avoid an unindexed LEFT JOIN that the v3.0.1 hotfix was
// about (per-model totals are cheap; the heavier per-turn aggregations
// still happen in the join-side query, but with a narrow filter).
//
// Returns null on any error (sqlite missing, schema drift, etc.) — the
// caller leaves the existing today state alone so a transient failure
// does not blank the row mid-day.
// ----------------------------------------------------------------------------
async function fetchTodayByModelFromSqlite() {
  try {
    if (!sqliteModPromise) sqliteModPromise = import("node:sqlite");
    const { DatabaseSync } = await sqliteModPromise;
    if (!sqliteDb || sqliteDbPath !== SQLITE_DEFAULT_PATH) {
      if (sqliteDb) { try { sqliteDb.close(); } catch {} }
      sqliteDb = new DatabaseSync(SQLITE_DEFAULT_PATH, { readOnly: true });
      sqliteDbPath = SQLITE_DEFAULT_PATH;
    }
    // Local midnight today, in JS milliseconds. token_usage.ts is also
    // milliseconds (Unix epoch * 1000).
    const now = new Date();
    const dayStart = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
    const dayStartMs = dayStart;
    const dayEndMs = dayStartMs + 86400 * 1000;

    // 1) turn_id -> LLM model name from assistant message rows.
    //    The data_json blob is small per row; the predicate is indexed by
    //    the (session_id, msg_id) unique index plus a row scan on
    //    created_at_ms.  We only look at today's rows.
    const msgRows = sqliteDb.prepare(
      "SELECT turn_id, " +
        "json_extract(data_json, '$.context_usage_telemetry.model') AS model " +
      "FROM local_runtime_message_rows " +
      "WHERE role = 'assistant' " +
        "AND turn_id IS NOT NULL " +
        "AND created_at_ms >= ? " +
        "AND created_at_ms < ? " +
        "AND json_extract(data_json, '$.context_usage_telemetry.model') IS NOT NULL"
    ).all(dayStartMs, dayEndMs);

    const turnToModel = new Map();
    for (const r of msgRows) {
      if (r.turn_id && r.model) turnToModel.set(r.turn_id, r.model);
    }

    // 2) Aggregate token_usage today per model.
    const tokRows = sqliteDb.prepare(
      "SELECT turn_id, session_id, " +
        "input_tokens, output_tokens, cache_read_tokens, cache_write_tokens " +
      "FROM local_runtime_token_usage " +
      "WHERE ts >= ? AND ts < ?"
    ).all(dayStartMs, dayEndMs);

    const agg = new Map();
    let matched = 0;
    for (const r of tokRows) {
      const model = (r.turn_id && turnToModel.get(r.turn_id)) || null;
      const key = model || "<unknown>";
      if (model) matched++;
      let a = agg.get(key);
      if (!a) { a = { in: 0, out: 0, cr: 0, cw: 0, turns: new Set(), sessions: new Set() }; agg.set(key, a); }
      a.in += r.input_tokens || 0;
      a.out += r.output_tokens || 0;
      a.cr += r.cache_read_tokens || 0;
      a.cw += r.cache_write_tokens || 0;
      if (r.turn_id) a.turns.add(r.turn_id);
      if (r.session_id) a.sessions.add(r.session_id);
    }
    const items = [];
    for (const [model, a] of agg) {
      items.push({
        model,
        total: a.in + a.out + a.cr + a.cw,
        input: a.in, output: a.out, cacheRead: a.cr, cacheWrite: a.cw,
        turns: a.turns.size, sessions: a.sessions.size,
      });
    }
    items.sort((x, y) => y.total - x.total);
    today = { valid: true, items, fetchedAt: Date.now(), dayStartMs, matched };
    pendingPlaceholders.todayByModel = false;
    return items;
  } catch {
    return null;
  }
}

async function fetchTodayByModelOnce() {
  // If the day boundary has rolled over since the last fetch, force a
  // refresh — otherwise we'd keep showing yesterday's totals after 00:00.
  const now = new Date();
  const dayStart = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
  const dayRollover = today.fetchedAt && today.dayStartMs !== dayStart;
  if (today.valid && !dayRollover && Date.now() - today.fetchedAt < TODAY_TTL_MS) return;
  const items = await fetchTodayByModelFromSqlite();
  if (items) requestRefresh();
}

// Render the today-by-model row. Returns an array of strings (one per
// line). The caller appends the array to lines only if non-empty.
// width is the column budget for one line. We pick the top-N models
// that fit:
//   width >= 100:  up to 5 models on one line
//   width >= 70:   up to 3 models
//   else:          1 model
// If even 1 model does not fit, return [] (drop the row entirely).
function renderTodayByModelRow(width) {
  if (!today.valid) return [];
  if (today.items.length === 0) return [];
  // Drop the synthetic <unknown> bucket from the visible list — it's only
  // useful for debugging. If that is the only bucket, the row is empty.
  const visible = today.items.filter((it) => it.model !== "<unknown>");
  if (visible.length === 0) return [];
  const maxN = width >= 100 ? 5 : width >= 70 ? 3 : 1;
  const items = visible.slice(0, maxN);
  const buildOne = (it) => {
    // 「model」 total — model in muted CJK brackets, total in the same
    // success-green family as 会话 tokens for visual consistency. Long
    // custom model names (GGUF filenames, fine-tunes) are middle-ellipsised
    // by shortenModelName so a 56-char filename doesn't blow the row width.
    const modelStr = shortenModelName(it.model);
    const totalStr = fmtTok(it.total);
    return "\u300c" + label(modelStr) + "\u300d " + ESC + C_SUCCESS + "m" + totalStr + RESET_SEQ;
  };
  // Build the longest possible line first, then trim from the right
  // until it fits in width. The first model is always kept so the
  // row never becomes empty as long as the user has any data.
  let chosen = [];
  for (let n = items.length; n >= 1; n--) {
    const lineParts = [];
    lineParts.push(label(L_TODAY) + " ");
    for (let i = 0; i < n; i++) {
      if (i > 0) lineParts.push(SEP);
      lineParts.push(buildOne(items[i]));
    }
    const line = lineParts.join("");
    if (dw(line) <= width) { chosen = [line]; break; }
  }
  return chosen;
}

function placeholderToday() {
  if (!pendingPlaceholders.todayByModel) return null;
  return muted(L_TODAY + " \u2026");
}

